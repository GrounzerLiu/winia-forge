//! Generated Rust constants for values the application needs at runtime.
//!
//! The app must not parse winia.toml: Android cannot read it at runtime, and the file is a build
//! input. Instead every build writes 'src/winia_config.rs' from the configuration, so editing
//! winia.toml and rebuilding updates the UI without touching user code.

use crate::config::WiniaConfig;
use anyhow::{Context, Result};
use std::path::Path;

pub const FILE: &str = "src/winia_config.rs";

/// Render the module. Values are emitted as Rust literals.
pub fn render(config: &WiniaConfig) -> String {
    let mut out = String::new();
    out.push_str("//! Generated by Winia Forge from winia.toml; do not edit.\n");
    out.push_str("//! Regenerated by 'winia build', so change winia.toml instead.\n\n");
    out.push_str(&format!(
        "pub const WINDOW_TITLE: &str = {:?};\n",
        config.window.title
    ));
    out.push_str(&format!(
        "pub const WINDOW_WIDTH: f32 = {:.1};\n",
        config.window.width
    ));
    out.push_str(&format!(
        "pub const WINDOW_HEIGHT: f32 = {:.1};\n",
        config.window.height
    ));
    out.push_str(&format!(
        "pub const WINDOW_RESIZABLE: bool = {};\n",
        config.window.resizable
    ));
    out.push_str(&format!(
        "pub const WINDOW_DECORATIONS: bool = {};\n",
        config.window.decorations
    ));
    out
}

/// Write the module when its content changed. Returns whether the file was rewritten.
pub fn write(root: &Path, config: &WiniaConfig) -> Result<bool> {
    let path = root.join(FILE);
    let contents = render(config);
    if std::fs::read_to_string(&path).ok().as_deref() == Some(contents.as_str()) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(&path, contents).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_window_values_as_literals() {
        let mut config = WiniaConfig::default();
        config.window.title = "My \"App\"".to_owned();
        config.window.width = 1280.0;
        config.window.height = 720.5;
        config.window.resizable = false;
        let module = render(&config);
        assert!(module.contains("pub const WINDOW_TITLE: &str = \"My \\\"App\\\"\";"));
        assert!(module.contains("pub const WINDOW_WIDTH: f32 = 1280.0;"));
        assert!(module.contains("pub const WINDOW_HEIGHT: f32 = 720.5;"));
        assert!(module.contains("pub const WINDOW_RESIZABLE: bool = false;"));
        assert!(module.contains("pub const WINDOW_DECORATIONS: bool = true;"));
    }
}
