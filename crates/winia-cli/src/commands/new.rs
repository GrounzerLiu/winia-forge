//! 'winia new' — create a minimal Winia application.
//!
//! The scaffold is deliberately small: a Cargo package, a shared UI function,
//! a winia.toml, and a README. Templates and platform scaffolds are the next
//! feature slice; see docs/02-feature-spec.md.

use crate::cli::{NewArgs, Platform};
use crate::config::WiniaConfig;
use anyhow::{Context, Result, bail};
use std::path::PathBuf;

const MAIN_RS: &str = r#"use winia::prelude::*;

#[composable]
fn app(ctx: &mut ComposeCtx) {
    Text::new("Hello, Winia!").build(ctx);
}

fn main() {
    winia::run_app!(|ctx| {
        WiniaTheme::auto(ctx, |ctx| {
            Window::new()
                .title("__APP_TITLE__")
                .size(1000.0, 700.0)
                .build(ctx, |ctx| {
                    app(ctx);
                });
        });
    });
}
"#;

pub fn run(args: NewArgs) -> Result<()> {
    let root = args.path.unwrap_or_else(|| PathBuf::from(&args.name));
    if root.exists() {
        let mut entries =
            std::fs::read_dir(&root).with_context(|| format!("reading {}", root.display()))?;
        if entries.next().is_some() {
            bail!("{} already exists and is not empty", root.display());
        }
    }
    std::fs::create_dir_all(root.join("src"))?;

    let package = package_name(&args.name)?;
    let binary = package.clone();
    let platforms = effective_platforms(&args.platforms);
    let winia_dependency = match args
        .winia_path
        .clone()
        .or_else(|| std::env::var_os("WINIA_PATH").map(PathBuf::from))
    {
        Some(path) => format!(
            "winia = {{ path = \"{}\" }}",
            path.display().to_string().replace('\\', "/")
        ),
        None => "winia = \"0.2\"".to_owned(),
    };

    let cargo_toml = format!(
        r#"[package]
name = "{package}"
version = "0.1.0"
edition = "2024"

[dependencies]
{winia_dependency}

[[bin]]
name = "{binary}"
path = "src/main.rs"
"#
    );
    write(&root.join("Cargo.toml"), cargo_toml)?;

    let main_rs = MAIN_RS.replace("__APP_TITLE__", &args.name);
    write(&root.join("src").join("main.rs"), main_rs)?;

    let mut config = WiniaConfig::default();
    config.app.name = args.name.clone();
    config.app.id = format!("com.example.{}", package.replace('-', "_"));
    config.android.package = config.app.id.clone();
    config.window.title = args.name.clone();
    config.save(&root.join("winia.toml"))?;

    write(&root.join(".gitignore"), "/target\n/dist\n*.apk\n*.aab\n")?;
    write(&root.join("README.md"), readme(&args.name))?;

    if platforms.contains(&Platform::Android) {
        std::fs::create_dir_all(root.join("android"))?;
        write(
            &root.join("android").join("README.md"),
            "# Android target\n\n\
             The Android Gradle scaffold is generated by 'winia platform add android' / \
             'winia android sync'; see docs/03-android-support.md in the Winia Forge repository.\n",
        )?;
    }

    if !args.no_git {
        let _ = std::process::Command::new("git")
            .arg("init")
            .current_dir(&root)
            .status();
    }

    println!("Created {} at {}", args.name, root.display());
    println!("Next:");
    println!("  cd {}", root.display());
    println!("  winia doctor");
    println!("  winia run");
    Ok(())
}

fn effective_platforms(requested: &[Platform]) -> Vec<Platform> {
    if requested.is_empty() {
        vec![Platform::Windows, Platform::Macos, Platform::Linux]
    } else {
        requested.to_vec()
    }
}

fn package_name(name: &str) -> Result<String> {
    let package = name.trim().to_lowercase().replace(' ', "-");
    if package.is_empty() {
        bail!("application name must not be empty");
    }
    if !package
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        bail!("application name may only contain ASCII letters, digits, '-' and '_'");
    }
    Ok(package)
}

fn write(path: &std::path::Path, content: impl AsRef<[u8]>) -> Result<()> {
    std::fs::write(path, content).with_context(|| format!("writing {}", path.display()))
}

fn readme(name: &str) -> String {
    format!(
        "# {name}\n\n\
         A Winia application.\n\n\
         Run:\n\n\
         \x20   winia run\n\
         \x20   winia build --release\n\n\
         Configuration lives in winia.toml.\n"
    )
}
