//! 'winia android sync' regenerates the Gradle files that Winia owns.
//!
//! Only build configuration is managed. Files without the generated header are left alone unless
//! --force is passed, so a project that hand-edited its Gradle setup is never silently rewritten.

use crate::cli::{AndroidArgs, AndroidCommand};
use crate::commands::new;
use crate::config::WiniaConfig;
use anyhow::{Context, Result, bail};
use std::path::Path;

/// Marker every managed file carries in its first line.
pub const MARKER: &str = "Generated by Winia Forge";

pub fn run(args: AndroidArgs) -> Result<()> {
    match args.command {
        AndroidCommand::Sync { check, force, json } => sync(check, force, json),
        AndroidCommand::Init { force } => android_init(force),
        AndroidCommand::Studio => {
            let root = project_root()?;
            super::studio::open(&root.join("android"))
        }
    }
}

fn android_init(force: bool) -> Result<()> {
    let root = project_root()?;
    if root.join("android").exists() && !force {
        bail!("android/ already exists; pass --force to regenerate it");
    }
    let config_path = root.join("winia.toml");
    let mut config = WiniaConfig::load(&config_path)?;
    config.validate()?;
    if config.android.package.trim().is_empty() {
        config.android.package = config.app.id.clone();
        config.save(&config_path)?;
    }
    crate::commands::init::ensure_android_cargo(&root, None)?;
    crate::commands::init::scaffold_android(&root, &config)?;
    println!("Next:");
    println!("  winia doctor --target android");
    println!("  winia build --target android");
    Ok(())
}

fn project_root() -> Result<std::path::PathBuf> {
    let cwd = std::env::current_dir().context("reading the current directory")?;
    let config_path = crate::config::find_config(&cwd)
        .ok_or_else(|| anyhow::anyhow!("winia.toml not found; run this inside a Winia project"))?;
    Ok(config_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .to_path_buf())
}

fn sync(check: bool, force: bool, json: bool) -> Result<()> {
    let root = project_root()?;
    let config = WiniaConfig::load(&root.join("winia.toml"))?;
    config.validate()?;
    if !root.join("android").is_dir() {
        bail!("no android/ directory; create the project with 'winia new --platforms android'");
    }

    let owned = render_vars(&root, &config);
    let vars: Vec<(&str, &str)> = owned
        .iter()
        .map(|(key, value)| (*key, value.as_str()))
        .collect();
    let mut entries = Vec::new();
    let mut pending = 0usize;
    for file in new::managed_android_files() {
        let destination = new::render(file.destination, &vars);
        let contents = new::render(file.template, &vars);
        let path = root.join(&destination);
        let existing = std::fs::read_to_string(&path).ok();
        let status = match &existing {
            None => "created",
            Some(current) if *current == contents => "unchanged",
            Some(current) if current.contains(MARKER) || force => "updated",
            Some(_) => "skipped",
        };
        if status != "unchanged" {
            pending += 1;
        }
        if !check && matches!(status, "created" | "updated") {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("creating {}", parent.display()))?;
            }
            std::fs::write(&path, &contents)
                .with_context(|| format!("writing {}", path.display()))?;
        }
        entries.push((destination, status));
    }

    if json {
        let values: Vec<_> = entries
            .iter()
            .map(|(path, status)| serde_json::json!({ "path": path, "status": status }))
            .collect();
        println!(
            "{}",
            serde_json::to_string_pretty(&serde_json::json!({
                "dry_run": check,
                "changed": pending,
                "files": values,
            }))?
        );
    } else {
        for (path, status) in &entries {
            let note = if *status == "skipped" {
                " (kept: no generated header, pass --force to overwrite)"
            } else {
                ""
            };
            println!("{status:<10} {path}{note}");
        }
        if check {
            println!("{pending} file(s) would change");
        }
    }

    if check && pending > 0 {
        std::process::exit(1);
    }
    Ok(())
}

fn render_vars(root: &Path, config: &WiniaConfig) -> [(&'static str, String); 4] {
    [
        ("__APP_NAME__", config.app.name.clone()),
        ("__APP_ID__", config.android.package.clone()),
        ("__PACKAGE_NAME__", cargo_package_name(root, config)),
        ("__VERSION__", config.app.version.clone()),
    ]
}

/// The Cargo package name, which settings.gradle uses as the Gradle project name. It is not in
/// winia.toml, so read Cargo.toml and fall back to the last segment of the app id.
fn cargo_package_name(root: &Path, config: &WiniaConfig) -> String {
    let parsed = std::fs::read_to_string(root.join("Cargo.toml"))
        .ok()
        .and_then(|text| text.parse::<toml::Value>().ok());
    parsed
        .as_ref()
        .and_then(|value| value.get("package"))
        .and_then(|package| package.get("name"))
        .and_then(|name| name.as_str())
        .map(str::to_owned)
        .unwrap_or_else(|| config.app.id.rsplit('.').next().unwrap_or("app").to_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_managed_template_carries_the_marker() {
        for file in new::managed_android_files() {
            assert!(
                file.template.contains(MARKER),
                "{} has no generated header",
                file.destination
            );
        }
    }

    #[test]
    fn managed_files_are_build_configuration_only() {
        for file in new::managed_android_files() {
            assert!(!file.destination.ends_with("AndroidManifest.xml"));
            assert!(!file.destination.ends_with(".java"));
        }
    }
}
