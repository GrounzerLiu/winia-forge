//! 'winia android sync' regenerates the Gradle files that Winia owns.
//!
//! Only build configuration is managed. Files without the generated header are left alone unless
//! --force is passed, so a project that hand-edited its Gradle setup is never silently rewritten.

use crate::cli::{AndroidArgs, AndroidCommand};
use crate::commands::new;
use crate::config::WiniaConfig;
use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

/// Marker every managed file carries in its first line.
pub const MARKER: &str = "Generated by Winia Forge";

pub fn run(args: AndroidArgs) -> Result<()> {
    match args.command {
        AndroidCommand::Sync { check, force, json } => sync(check, force, json),
        AndroidCommand::Init { force, winia_path } => android_init(force, winia_path),
    }
}

/// Shared by 'winia init --platforms android' and 'winia android init'.
pub(crate) fn android_init(force: bool, winia_path: Option<std::path::PathBuf>) -> Result<()> {
    let root = project_root()?;
    if root.join("android").exists() && !force {
        bail!("android/ already exists; pass --force to regenerate it");
    }
    let config_path = root.join("winia.toml");
    let mut config = WiniaConfig::load(&config_path)?;
    // Fill the package before validating: validate() rejects an empty [android].package, which is
    // exactly the state this command is meant to repair.
    // AndroidConfig::default() supplies com.example.myapp, so an absent [android] table is not
    // visible in the loaded value. Check the file itself and fall back to the real app id.
    if config.android.package.trim().is_empty() || !android_package_configured(&config_path) {
        // A bundle id may contain hyphens; an Android applicationId may not.
        config.android.package = config.app.id.replace('-', "_");
        crate::config::set_android_package(&config_path, &config.android.package)?;
    }
    config.validate()?;
    let previous_package = std::fs::read_to_string(root.join("android/app/build.gradle.kts"))
        .ok()
        .and_then(|text| namespace_of(&text))
        .or_else(|| existing_activity_package(&root));
    crate::commands::init::ensure_android_cargo(&root, winia_path, config.android.activity, force)?;
    crate::commands::init::scaffold_android(&root, &config)?;
    if let Some(previous) = previous_package
        && previous != config.android.package
    {
        let stale = root
            .join("android/app/src/main/java")
            .join(previous.replace('.', "/"))
            .join("MainActivity.java");
        let _ = std::fs::remove_file(stale);
    }
    println!("Next:");
    println!("  winia doctor --target android");
    println!("  winia build --target android");
    Ok(())
}

fn project_root() -> Result<std::path::PathBuf> {
    let cwd = std::env::current_dir().context("reading the current directory")?;
    let config_path = crate::config::find_config(&cwd)
        .ok_or_else(|| anyhow::anyhow!("winia.toml not found; run this inside a Winia project"))?;
    Ok(config_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .to_path_buf())
}

fn sync(check: bool, force: bool, json: bool) -> Result<()> {
    let root = project_root()?;
    let config = WiniaConfig::load(&root.join("winia.toml"))?;
    config.validate()?;
    if !root.join("android").is_dir() {
        bail!("no android/ directory; create the project with 'winia new --platforms android'");
    }

    // package is also baked into MainActivity.java and the manifest, which sync does not manage.
    // Refuse a silent mismatch: the Gradle namespace would move while the activity class stays.
    let expected_package = if config.android.package.trim().is_empty() {
        config.app.id.replace('-', "_")
    } else {
        config.android.package.clone()
    };
    let gradle_package = std::fs::read_to_string(root.join("android/app/build.gradle.kts"))
        .ok()
        .and_then(|text| namespace_of(&text));
    let activity_package = existing_activity_package(&root);
    for current in [gradle_package, activity_package].into_iter().flatten() {
        if current != expected_package {
            bail!(
                "android.package changed from '{current}' to '{expected_package}'; run 'winia android init --force' so MainActivity.java and AndroidManifest.xml move with it"
            );
        }
    }

    let owned = render_vars(&root, &config);
    let vars: Vec<(&str, &str)> = owned
        .iter()
        .map(|(key, value)| (*key, value.as_str()))
        .collect();
    let mut entries = Vec::new();
    let mut pending = 0usize;
    let mut skipped = 0usize;
    for file in new::managed_android_files() {
        let destination = new::render(file.destination, &vars);
        let contents = new::render(file.template, &vars);
        let path = root.join(&destination);
        let existing = std::fs::read_to_string(&path).ok();
        let status = classify(existing.as_deref(), &contents, force);
        match status {
            "created" | "updated" => pending += 1,
            "skipped" => skipped += 1,
            _ => {}
        }
        if !check && matches!(status, "created" | "updated") {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("creating {}", parent.display()))?;
            }
            std::fs::write(&path, &contents)
                .with_context(|| format!("writing {}", path.display()))?;
        }
        entries.push((destination, status));
    }

    // A missing Gradle wrapper cannot be regenerated by any other command; restore it here so the
    // build preflight's advice ("run winia android sync") is true.
    let wrapper = [
        "android/gradlew",
        "android/gradlew.bat",
        "android/gradle/wrapper/gradle-wrapper.jar",
    ];
    if wrapper.iter().any(|path| !root.join(path).is_file()) {
        if check {
            pending += 1;
            entries.push(("android/gradlew (+wrapper)".to_owned(), "missing"));
        } else {
            crate::commands::new::write_android_binaries(&root)?;
            entries.push(("android/gradlew (+wrapper)".to_owned(), "restored"));
        }
    }

    if json {
        let values: Vec<_> = entries
            .iter()
            .map(|(path, status)| serde_json::json!({ "path": path, "status": status }))
            .collect();
        println!(
            "{}",
            serde_json::to_string_pretty(&serde_json::json!({
                "dry_run": check,
                "changed": pending,
                "skipped": skipped,
                "files": values,
            }))?
        );
    } else {
        for (path, status) in &entries {
            let note = if *status == "skipped" {
                " (kept: no generated header, pass --force to overwrite)"
            } else {
                ""
            };
            println!("{status:<10} {path}{note}");
        }
        if check {
            let kept = if skipped > 0 {
                format!(" ({skipped} kept untouched)")
            } else {
                String::new()
            };
            println!("{pending} file(s) would change{kept}");
        }
    }

    if check && pending > 0 {
        std::process::exit(1);
    }
    Ok(())
}

/// What 'sync' would do to one managed file. Files without the generated header are only
/// rewritten when forced, so they never count as pending drift.
fn classify(existing: Option<&str>, contents: &str, force: bool) -> &'static str {
    match existing {
        None => "created",
        Some(current) if current == contents => "unchanged",
        Some(current) if current.contains(MARKER) || force => "updated",
        Some(_) => "skipped",
    }
}

fn android_package_configured(path: &Path) -> bool {
    std::fs::read_to_string(path)
        .ok()
        .and_then(|text| text.parse::<toml::Value>().ok())
        .and_then(|value| {
            value
                .get("android")
                .and_then(|android| android.get("package"))
                .map(|_| ())
        })
        .is_some()
}

/// When the managed Gradle file is missing, infer the package from the Java source tree so a
/// renamed android.package still cannot silently diverge from MainActivity.java.
fn existing_activity_package(root: &Path) -> Option<String> {
    fn find(directory: &Path, name: &str) -> Option<PathBuf> {
        for entry in std::fs::read_dir(directory).ok()?.flatten() {
            let path = entry.path();
            if path.is_dir() {
                if let Some(found) = find(&path, name) {
                    return Some(found);
                }
            } else if path.file_name().and_then(|value| value.to_str()) == Some(name) {
                return Some(path);
            }
        }
        None
    }
    let java = root.join("android/app/src/main/java");
    let activity = find(&java, "MainActivity.java")?;
    let package = activity.parent()?.strip_prefix(&java).ok()?;
    let segments: Vec<&str> = package
        .components()
        .filter_map(|component| component.as_os_str().to_str())
        .collect();
    (!segments.is_empty()).then(|| segments.join("."))
}

fn namespace_of(gradle: &str) -> Option<String> {
    gradle.lines().find_map(|line| {
        let line = line.trim();
        let value = line.strip_prefix("namespace = ")?;
        Some(value.trim_matches('"').to_owned())
    })
}

fn render_vars(root: &Path, config: &WiniaConfig) -> [(&'static str, String); 5] {
    [
        ("__APP_NAME__", config.app.name.clone()),
        (
            "__APP_NAME_KOTLIN__",
            crate::commands::new::kotlin_string(&config.app.name),
        ),
        ("__APP_ID__", config.android.package.clone()),
        ("__PACKAGE_NAME__", cargo_package_name(root, config)),
        ("__VERSION__", config.app.version.clone()),
    ]
}

/// The Cargo package name, which settings.gradle uses as the Gradle project name. It is not in
/// winia.toml, so read Cargo.toml and fall back to the last segment of the app id.
fn cargo_package_name(root: &Path, config: &WiniaConfig) -> String {
    let parsed = std::fs::read_to_string(root.join("Cargo.toml"))
        .ok()
        .and_then(|text| text.parse::<toml::Value>().ok());
    parsed
        .as_ref()
        .and_then(|value| value.get("package"))
        .and_then(|package| package.get("name"))
        .and_then(|name| name.as_str())
        .map(str::to_owned)
        .unwrap_or_else(|| config.app.id.rsplit('.').next().unwrap_or("app").to_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_managed_template_carries_the_marker() {
        for file in new::managed_android_files() {
            assert!(
                file.template.contains(MARKER),
                "{} has no generated header",
                file.destination
            );
        }
    }

    #[test]
    fn classifies_managed_files() {
        assert_eq!(classify(None, "body", false), "created");
        assert_eq!(classify(Some("body"), "body", false), "unchanged");
        assert_eq!(classify(Some("stale"), "body", true), "updated");
        let generated = format!("// {MARKER}\nstale");
        assert_eq!(classify(Some(&generated), "body", false), "updated");
        assert_eq!(classify(Some("hand written"), "body", false), "skipped");
    }

    #[test]
    fn managed_files_are_build_configuration_only() {
        for file in new::managed_android_files() {
            assert!(!file.destination.ends_with("AndroidManifest.xml"));
            assert!(!file.destination.ends_with(".java"));
        }
    }
}
