//! NSIS installer generation for Windows desktop builds.
//!
//! The generated script deliberately keeps the NSIS defaults:
//!
//! - RequestExecutionLevel is left out, so the installer requests administrator rights and
//!   installs for all users (per-machine install).
//! - Unicode is left out (NSIS defaults to true).
//! - SetCompressor is left out (NSIS defaults to zlib).
//!
//! Only values NSIS has no default for are written out: the install directory, Add/Remove
//! Programs entries, the Start Menu shortcut and the uninstaller. makensis is an external
//! tool: this module locates it, feeds it the script, and verifies the produced executable.

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};
use std::process::Command;

/// Everything the installer needs to know about one application.
pub struct InstallerSpec<'a> {
    pub app_name: &'a str,
    pub app_version: &'a str,
    /// Reverse-DNS application id; also names the uninstall registry key.
    pub app_id: &'a str,
    pub publisher: &'a str,
    /// File name of the main executable inside the payload.
    pub executable: &'a str,
    /// Staged directory to install (executable, assets, manifest).
    pub payload: &'a Path,
    /// Installer executable to produce.
    pub output: &'a Path,
    /// Icon file name inside the payload, used for shortcuts and Add/Remove Programs.
    pub icon: Option<&'a Path>,
    /// Install into $PROGRAMFILES64 (64-bit payload) instead of $PROGRAMFILES.
    pub program_files_64: bool,
}

/// Generate the script, compile it with makensis, and return the installer path.
pub fn build(spec: &InstallerSpec<'_>) -> Result<PathBuf> {
    if !spec.payload.is_dir() {
        bail!("payload directory not found: {}", spec.payload.display());
    }
    let script = generate(spec)?;
    let stem = spec
        .output
        .file_stem()
        .map(|value| value.to_string_lossy().into_owned())
        .unwrap_or_else(|| "installer".to_owned());
    let script_path = spec
        .payload
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(format!("{stem}.nsi"));
    if let Some(parent) = script_path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(&script_path, &script)
        .with_context(|| format!("writing {}", script_path.display()))?;

    let makensis = find_makensis()?;
    let output = Command::new(&makensis)
        .arg("/V2")
        .arg("/INPUTCHARSET")
        .arg("UTF8")
        .arg(&script_path)
        .current_dir(spec.payload)
        .output()
        .with_context(|| format!("running {}", makensis.display()))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        let detail = if stderr.trim().is_empty() {
            stdout
        } else {
            stderr
        };
        bail!("makensis failed ({}): {}", output.status, tail(&detail, 20));
    }
    if !spec.output.is_file() {
        bail!(
            "makensis reported success but {} was not produced",
            spec.output.display()
        );
    }
    Ok(spec.output.to_path_buf())
}

/// Render the nsi script for a spec. Kept separate so tests can assert its shape.
pub fn generate(spec: &InstallerSpec<'_>) -> Result<String> {
    let entries = payload_entries(spec.payload)?;
    if entries.files.is_empty() {
        bail!("payload directory is empty: {}", spec.payload.display());
    }
    let total_kib = entries.bytes / 1024;
    let programs = if spec.program_files_64 {
        "$PROGRAMFILES64"
    } else {
        "$PROGRAMFILES"
    };
    let name = escape(spec.app_name);
    let version = escape(spec.app_version);
    let publisher = escape(spec.publisher);
    let exe = escape(spec.executable);
    let key = format!(
        "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\{}",
        escape(spec.app_id)
    );
    let icon = spec
        .icon
        .and_then(|path| path.file_name())
        .and_then(|value| value.to_str())
        .map(escape);
    let mut s = String::new();

    s.push_str("; Generated by Winia Forge - do not edit.\n");
    s.push_str(";\n");
    s.push_str("; NSIS defaults kept on purpose:\n");
    s.push_str(";   RequestExecutionLevel  admin (per-machine install, UAC prompt)\n");
    s.push_str(";   Unicode                true\n");
    s.push_str(";   SetCompressor          zlib\n");
    s.push_str(";\n");
    s.push_str("; Everything below is a value NSIS has no default for.\n\n");

    s.push_str(&format!("Name \"{name} {version}\"\n"));
    s.push_str(&format!(
        "OutFile \"{}\"\n",
        escape(&forward_slashes(spec.output))
    ));
    s.push_str(&format!("InstallDir \"{programs}\\{name}\"\n"));
    s.push_str(&format!(
        "InstallDirRegKey HKLM \"{key}\" \"InstallLocation\"\n\n"
    ));

    s.push_str("!include \"MUI2.nsh\"\n\n");
    s.push_str(&format!("!define MUI_FINISHPAGE_RUN \"$INSTDIR\\{exe}\"\n"));
    s.push_str("!insertmacro MUI_PAGE_WELCOME\n");
    s.push_str("!insertmacro MUI_PAGE_DIRECTORY\n");
    s.push_str("!insertmacro MUI_PAGE_INSTFILES\n");
    s.push_str("!insertmacro MUI_PAGE_FINISH\n");
    s.push_str("!insertmacro MUI_UNPAGE_CONFIRM\n");
    s.push_str("!insertmacro MUI_UNPAGE_INSTFILES\n");
    s.push_str("!insertmacro MUI_LANGUAGE \"English\"\n\n");

    s.push_str("Function .onInit\n");
    s.push_str("  SetShellVarContext all\n");
    s.push_str("FunctionEnd\n\n");
    s.push_str("Function un.onInit\n");
    s.push_str("  SetShellVarContext all\n");
    s.push_str("FunctionEnd\n\n");

    s.push_str("Section \"Program files\"\n");
    s.push_str("  SectionIn Ro\n");
    s.push_str("  SetOutPath \"$INSTDIR\"\n");
    s.push_str(&format!(
        "  File /r \"{}\\*.*\"\n",
        escape(&forward_slashes(spec.payload))
    ));
    s.push_str("  WriteUninstaller \"$INSTDIR\\Uninstall.exe\"\n\n");

    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"DisplayName\" \"{name}\"\n"
    ));
    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"DisplayVersion\" \"{version}\"\n"
    ));
    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"Publisher\" \"{publisher}\"\n"
    ));
    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"InstallLocation\" \"$INSTDIR\"\n"
    ));
    match &icon {
        Some(icon) => s.push_str(&format!(
            "  WriteRegStr HKLM \"{key}\" \"DisplayIcon\" \"$INSTDIR\\{icon},0\"\n"
        )),
        None => s.push_str(&format!(
            "  WriteRegStr HKLM \"{key}\" \"DisplayIcon\" \"$INSTDIR\\{exe}\"\n"
        )),
    }
    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"UninstallString\" '\"$INSTDIR\\Uninstall.exe\"'\n"
    ));
    s.push_str(&format!(
        "  WriteRegStr HKLM \"{key}\" \"QuietUninstallString\" '\"$INSTDIR\\Uninstall.exe\" /S'\n"
    ));
    s.push_str(&format!("  WriteRegDWORD HKLM \"{key}\" \"NoModify\" 1\n"));
    s.push_str(&format!("  WriteRegDWORD HKLM \"{key}\" \"NoRepair\" 1\n"));
    s.push_str(&format!(
        "  WriteRegDWORD HKLM \"{key}\" \"EstimatedSize\" {total_kib}\n"
    ));
    s.push_str("SectionEnd\n\n");

    s.push_str("Section \"Start Menu shortcut\"\n");
    s.push_str(&format!(
        "  CreateShortcut /NoWorkingDir \"$SMPROGRAMS\\{name}.lnk\" \"$INSTDIR\\{exe}\"\n"
    ));
    s.push_str("SectionEnd\n\n");

    s.push_str("Section \"Uninstall\"\n");
    s.push_str("  SetShellVarContext all\n");
    s.push_str(&format!("  Delete \"$SMPROGRAMS\\{name}.lnk\"\n"));
    s.push_str("  Delete \"$INSTDIR\\Uninstall.exe\"\n");
    for file in &entries.files {
        s.push_str(&format!(
            "  Delete \"$INSTDIR\\{}\"\n",
            escape(&back_slashes(file))
        ));
    }
    for dir in &entries.directories {
        s.push_str(&format!(
            "  RMDir \"$INSTDIR\\{}\"\n",
            escape(&back_slashes(dir))
        ));
    }
    s.push_str("  RMDir \"$INSTDIR\"\n");
    s.push_str(&format!("  DeleteRegKey HKLM \"{key}\"\n"));
    s.push_str("SectionEnd\n");

    Ok(s)
}

struct PayloadEntries {
    /// Forward-slash relative paths of every file, sorted.
    files: Vec<String>,
    /// Forward-slash relative directories, deepest first (ready for RMDir).
    directories: Vec<String>,
    bytes: u64,
}

fn payload_entries(payload: &Path) -> Result<PayloadEntries> {
    let mut files = Vec::new();
    let mut directories = Vec::new();
    let mut bytes = 0u64;
    collect(payload, payload, &mut files, &mut directories, &mut bytes)?;
    files.sort();
    directories.sort_by_key(|dir| std::cmp::Reverse(dir.matches('/').count()));
    Ok(PayloadEntries {
        files,
        directories,
        bytes,
    })
}

fn collect(
    root: &Path,
    directory: &Path,
    files: &mut Vec<String>,
    directories: &mut Vec<String>,
    bytes: &mut u64,
) -> Result<()> {
    for entry in
        std::fs::read_dir(directory).with_context(|| format!("reading {}", directory.display()))?
    {
        let entry = entry?;
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_symlink() {
            continue;
        }
        if file_type.is_dir() {
            if let Ok(relative) = path.strip_prefix(root) {
                directories.push(relative.to_string_lossy().replace('\\', "/"));
            }
            collect(root, &path, files, directories, bytes)?;
        } else if file_type.is_file() {
            *bytes += entry.metadata().map(|meta| meta.len()).unwrap_or(0);
            if let Ok(relative) = path.strip_prefix(root) {
                files.push(relative.to_string_lossy().replace('\\', "/"));
            }
        }
    }
    Ok(())
}

/// NSIS treats the dollar sign as a variable prefix and the double quote as a delimiter.
fn escape(value: &str) -> String {
    value.replace('$', "$$").replace('"', "$\"")
}

fn forward_slashes(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

fn back_slashes(relative: &str) -> String {
    relative.replace('/', "\\")
}

fn tail(text: &str, lines: usize) -> String {
    let collected: Vec<&str> = text.lines().collect();
    let start = collected.len().saturating_sub(lines);
    collected[start..].join("\n")
}

/// Locate makensis: explicit environment override, PATH, the install directory, then the
/// uninstall registry entry the official installer writes.
pub fn find_makensis() -> Result<PathBuf> {
    let exe = if cfg!(windows) {
        "makensis.exe"
    } else {
        "makensis"
    };
    if let Some(path) = std::env::var_os("MAKENSIS") {
        let path = PathBuf::from(path);
        if path.is_file() {
            return Ok(path);
        }
    }
    if let Some(dir) = std::env::var_os("NSISDIR") {
        let candidate = PathBuf::from(dir).join(exe);
        if candidate.is_file() {
            return Ok(candidate);
        }
    }
    if let Some(found) = path_lookup(exe) {
        return Ok(found);
    }
    if cfg!(windows) {
        for key in ["ProgramFiles(x86)", "ProgramFiles"] {
            if let Some(dir) = std::env::var_os(key) {
                let candidate = PathBuf::from(dir).join("NSIS").join(exe);
                if candidate.is_file() {
                    return Ok(candidate);
                }
            }
        }
        if let Some(dir) = registry_install_location() {
            let candidate = dir.join(exe);
            if candidate.is_file() {
                return Ok(candidate);
            }
        }
    }
    bail!(
        "makensis not found; install NSIS (winget install NSIS.NSIS, or apt-get install nsis) or set NSISDIR/MAKENSIS"
    )
}

fn path_lookup(exe: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path) {
        let candidate = dir.join(exe);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    None
}

#[cfg(windows)]
fn registry_install_location() -> Option<PathBuf> {
    let output = Command::new("reg")
        .args([
            "query",
            r"HKLM\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\NSIS",
            "/v",
            "InstallLocation",
        ])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&output.stdout);
    let line = text.lines().find(|line| line.contains("InstallLocation"))?;
    let value = line.split("REG_SZ").nth(1)?.trim();
    if value.is_empty() {
        None
    } else {
        Some(PathBuf::from(value))
    }
}

#[cfg(not(windows))]
fn registry_install_location() -> Option<PathBuf> {
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec<'a>(payload: &'a Path, output: &'a Path) -> InstallerSpec<'a> {
        InstallerSpec {
            app_name: "Winia Blank",
            app_version: "0.1.3",
            app_id: "com.example.winia_blank",
            publisher: "Winia contributors",
            executable: "winia-blank.exe",
            payload,
            output,
            icon: None,
            program_files_64: true,
        }
    }

    fn fixture(name: &str) -> PathBuf {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../target")
            .join(format!("nsis-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let payload = root.join("payload");
        std::fs::create_dir_all(payload.join("assets")).unwrap();
        std::fs::write(payload.join("app.exe"), b"exe").unwrap();
        std::fs::write(payload.join("assets/logo.png"), b"png").unwrap();
        root
    }

    #[test]
    fn keeps_the_nsis_defaults_and_declares_the_rest() {
        let root = fixture("defaults");
        let script = generate(&spec(&root.join("payload"), &root.join("setup.exe"))).unwrap();
        let directives: Vec<&str> = script
            .lines()
            .map(str::trim_start)
            .filter(|line| !line.starts_with(';'))
            .collect();
        assert!(
            !directives
                .iter()
                .any(|line| line.starts_with("RequestExecutionLevel"))
        );
        assert!(
            !directives
                .iter()
                .any(|line| line.starts_with("SetCompressor"))
        );
        assert!(!directives.iter().any(|line| line.starts_with("Unicode ")));
        assert!(script.contains("InstallDir \"$PROGRAMFILES64\\Winia Blank\""));
        assert!(script.contains("Delete \"$INSTDIR\\app.exe\""));
        assert!(script.contains("Delete \"$INSTDIR\\assets\\logo.png\""));
        assert!(script.contains("RMDir \"$INSTDIR\\assets\""));
        assert!(script.contains("DeleteRegKey HKLM"));
        std::fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn escapes_dollars_and_quotes() {
        assert_eq!(escape("a$b"), "a$$b");
        assert_eq!(escape("say \"hi\""), "say $\"hi$\"");
    }
}
